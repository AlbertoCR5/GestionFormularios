package com.albertocr.gestionformularios.model;

/**
 * Enumera los tipos de elecciones sindicales posibles.
 *
 * @author Alberto Castro <AlbertoCastroCR>
 * @version 1.0
 */
public enum TipoEleccion {
    /**
     * Representa una elección de Delegados de Personal, típicamente en empresas de menos de 50 trabajadores.
     */
    DELEGADOS,

    /**
     * Representa una elección de Comité de Empresa, típicamente en empresas de 50 o más trabajadores.
     */
    COMITE
}
